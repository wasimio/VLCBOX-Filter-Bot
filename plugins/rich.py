from pyrogram import filters, enums, Client
from pyrogram.types import Message, CallbackQuery
from VLCBox.util.base_clients import MainBot
from VLCBox.util.rich import send_rich_message_api
from info import RICH_MOVIE_RESULTS

logger = logging.getLogger(__name__)
print(">>> VLCBox: plugins.rich successfully loaded <<<")


# ─────────────────────────────────────────────────────────────────────────────
# DIAGNOSTIC
# ─────────────────────────────────────────────────────────────────────────────

@MainBot.on_message(filters.command(["richtestping", "richping"]) & filters.incoming, group=1)
async def rich_test_ping_command(client, message: Message):
    """
    Diagnostic handler to verify whether the Rich plugin is properly loaded.
    Does NOT call Telegram's Rich Message API.
    """
    logger.info(f"RICH_DIAGNOSTIC: /richtestping received in chat_id={message.chat.id}")
    await message.reply_text("RICH PLUGIN LOADED ✅")


# ─────────────────────────────────────────────────────────────────────────────
# /testrich — Minimal PoC with a native Rich button block
# ─────────────────────────────────────────────────────────────────────────────

@MainBot.on_message(filters.command("testrich") & filters.incoming, group=1)
async def test_rich_command(client, message: Message):
    """
    Isolated test command for Telegram Rich Messages.
    Demonstrates a heading, paragraph, divider, and a buttons block (not reply_markup).
    """
    chat_id = message.chat.id
    logger.info(f"RICH_TEST: /testrich received in chat_id={chat_id}")

    blocks = [
        {
            "type": "heading",
            "text": {"type": "plain", "text": "🎬 VLCBox Rich Message Test"},
            "size": 1
        },
        {
            "type": "paragraph",
            "text": {"type": "plain", "text": "This is a genuine Telegram Rich Message generated by VLCBox. Buttons below are INSIDE the rich message."}
        },
        {
            "type": "divider"
        },
        {
            "type": "buttons",
            "buttons": [
                {
                    "text": "✅ TEST BUTTON",
                    "style": "primary",
                    "callback_data": "rich_test_btn_clicked"
                }
            ]
        }
    ]

    try:
        res = await send_rich_message_api(
            client=client,
            chat_id=chat_id,
            blocks=blocks,
            reply_to_message_id=message.id
        )

        if not res.get("success"):
            error_desc = res.get("description", res.get("error", "Unknown API error"))
            status_code = res.get("status_code", "Unknown")
            logger.warning(f"RICH_TEST: sendRichMessage failure: {status_code} - {error_desc}")
            await message.reply_text(
                f"⚠️ <b>Telegram Rich Message API Test Result</b>\n\n"
                f"<b>Status:</b> <code>Rejected / Failed</code>\n"
                f"<b>HTTP Code:</b> <code>{status_code}</code>\n"
                f"<b>Telegram API Response:</b> <code>{error_desc}</code>\n\n"
                f"<i>Note: Rich Messages are currently in experimental testing (RICH_MOVIE_RESULTS={RICH_MOVIE_RESULTS}).</i>",
                parse_mode=enums.ParseMode.HTML
            )
        else:
            logger.info(f"RICH_TEST: sendRichMessage succeeded for chat_id={chat_id}")
    except Exception as e:
        logger.error(f"RICH_TEST: Exception executing /testrich: {e}", exc_info=True)
        await message.reply_text(
            f"❌ <b>Rich Handler Exception:</b> <code>{html.escape(str(e))}</code>",
            parse_mode=enums.ParseMode.HTML
        )


