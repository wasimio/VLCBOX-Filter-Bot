"""
Experimental Telegram Rich Message Plugin for VLCBox.

Provides:
- /richtestping: Diagnostic ping command to verify plugin loading.
- /testrich: Minimal Rich Message API proof of concept with a buttons block.
- /richmovie: Static Rich Movie UI Prototype using structured blocks with native
  RichMessageButton rows INSIDE rich_message.blocks (no reply_markup keyboard).
- Isolated callback handlers for all prototype buttons.

Bot API 10.3: Uses InputRichBlockButtons with RichMessageButton objects.
Buttons are part of the rich message content, NOT a traditional inline keyboard.
"""

import html
