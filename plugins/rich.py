"""
Experimental Telegram Rich Message Proof of Concept Plugin for VLCBox.

Provides:
- /testrich: Tests genuine Telegram Rich Message sending in private chat and groups.
- Callback handler for [TEST BUTTON]
"""

import logging
from pyrogram import filters, enums, Client
from pyrogram.types import Message, CallbackQuery
from VLCBox.util.base_clients import MainBot
from VLCBox.util.rich import send_rich_message_api
from info import RICH_MOVIE_RESULTS

logger = logging.getLogger(__name__)


@MainBot.on_message(filters.command("testrich") & filters.incoming)
async def test_rich_command(client: MainBot, message: Message):
    """
    Isolated test command for Telegram Rich Messages.
    Works in both private chat and groups/supergroups.
    """
    chat_id = message.chat.id
    
    # Construct minimal rich blocks according to specification
    blocks = [
        {
            "type": "heading",
            "text": "🎬 VLCBox Rich Message Test"
        },
        {
            "type": "paragraph",
            "text": "This is a genuine Telegram Rich Message generated by VLCBox."
        },
        {
            "type": "divider"
        },
        {
            "type": "list",
            "items": [
                {"text": "Rich formatting"},
                {"text": "Structured blocks"},
                {"text": "Telegram-native rendering"}
            ]
        },
        {
            "type": "table",
            "headers": ["Quality", "Size"],
            "rows": [
                ["1080p", "3.2 GB"],
                ["720p", "1.8 GB"]
            ]
        }
    ]

    reply_markup = {
        "inline_keyboard": [
            [{"text": "TEST BUTTON", "callback_data": "rich_test_btn_clicked"}]
        ]
    }

    # Call genuine Telegram Rich Message API directly
    res = await send_rich_message_api(
        client=client,
        chat_id=chat_id,
        blocks=blocks,
        reply_markup=reply_markup,
        reply_to_message_id=message.id
    )

    if not res.get("success"):
        error_desc = res.get("description", res.get("error", "Unknown API error"))
        status_code = res.get("status_code", "Unknown")
        await message.reply_text(
            f"⚠️ <b>Telegram Rich Message API Test Result</b>\n\n"
            f"<b>Status:</b> <code>Rejected / Failed</code>\n"
            f"<b>HTTP Code:</b> <code>{status_code}</code>\n"
            f"<b>Telegram API Response:</b> <code>{error_desc}</code>\n\n"
            f"<i>Note: Rich Messages are currently in experimental testing (RICH_MOVIE_RESULTS={RICH_MOVIE_RESULTS}).</i>",
            parse_mode=enums.ParseMode.HTML
        )


@MainBot.on_callback_query(filters.regex(r"^rich_test_btn_clicked$"))
async def rich_test_callback_handler(client: Client, query: CallbackQuery):
    """
    Isolated callback handler for the test Rich Message button.
    """
    await query.answer("✅ Rich Message button works.", show_alert=True)
